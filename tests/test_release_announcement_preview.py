"""§151: the announcement copy is prepared before the tag, by a tool that writes no remote branch.

The pipeline used to render the copy from the *published* release and commit it to the default
branch from inside `publish.yml`. That write cannot succeed on a `main` protected with `ci` required
and `strict: true`: the commit a tag may name is exactly the commit whose `ci` ran while the tag was
still missing (§149, run 37919265633 → 409). So the copy is now generated by
`scripts/generate_release_announcement.py --preview` on the release branch, rides the release PR, and
`publish.yml` only verifies the tree it built.

Two honesty rules the tests below exist to keep:

* a preview may not assert a publication date it cannot observe;
* a preview may not render highlights it does not have -- a missing CHANGELOG section is an error,
  never a placeholder that reads like a release summary.
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest

from scripts import generate_release_announcement as gen

REPO = "Jackxiaozhiren/data-science-agent"

CHANGELOG = """# Changelog

## Unreleased — Something still in flight

- not part of any release yet

## 4.6.0 — Provenance Track (minor, no breaking change)

### Measured

- coverage reached 84%

### Added

- a `dsa provenance` command

## 4.5.0 — Quality-gate hardening (minor, no breaking change)

- the previous release
"""


def test_changelog_highlights_slices_by_heading_level() -> None:
    """`### ` subsections belong to the section; the next `## ` ends it."""
    text = gen.changelog_highlights(CHANGELOG, "4.6.0")
    assert text.startswith("### Measured"), text[:40]
    assert "a `dsa provenance` command" in text
    assert "4.5.0" not in text, "the slice ran past the next level-two heading"
    assert "Still in flight" not in text, "the slice ran backwards into Unreleased"


def test_a_missing_section_is_an_error_not_a_placeholder() -> None:
    """Rendering highlights from a release nobody described yet would ship prose as fact."""
    with pytest.raises(gen.SectionNotFound) as excinfo:
        gen.changelog_highlights(CHANGELOG, "9.9.9")
    message = str(excinfo.value)
    assert "## 9.9.9" in message and "Unreleased" in message, message


def test_preview_carries_no_publication_claim() -> None:
    """The date is unknowable before the tag; an invented one is the defect class §149 documents."""
    text = gen.preview("v4.6.0", CHANGELOG, REPO)
    assert "Released" not in text
    assert not re.search(r"\b\d{4}-\d{2}-\d{2}\b", text), "a date appeared in a pre-tag copy"
    assert text.splitlines()[0] == "# Data Science Agent v4.6.0"
    assert f"https://github.com/{REPO}/releases/tag/v4.6.0" in text
    assert "a `dsa provenance` command" in text


def test_from_release_keeps_the_observed_date_and_body() -> None:
    """Backfill mode reads a real release, so it may print what that release reported."""
    text = gen.render(
        "v4.4.0",
        {
            "body": "Verified release notes.",
            "published_at": "2026-09-11T08:00:00Z",
            "html_url": f"https://github.com/{REPO}/releases/tag/v4.4.0",
        },
    )
    assert "# Data Science Agent v4.4.0" in text.splitlines()[0]
    assert "Released 2026-09-11" in text
    assert "Verified release notes." in text


def test_both_modes_round_trip_through_the_title_reader() -> None:
    """`check_public_claims` reads the version back out of the title line; both forms must agree."""
    assert gen.title_version(gen.preview("v4.6.0", CHANGELOG, REPO)) == "4.6.0"
    assert (
        gen.title_version(gen.render("v4.4.0", {"body": "x", "published_at": "", "html_url": "y"}))
        == "4.4.0"
    )
    assert gen.title_version("no title here") is None


def test_copies_are_written_into_the_tree_and_idempotent(tmp_path: Path) -> None:
    text = gen.preview("v4.6.0", CHANGELOG, REPO)
    written = gen.write_copies(tmp_path, "v4.6.0", text)
    assert [p.name for p in written] == ["v4.6.0.md", "latest.md"]
    for path in written:
        assert path.read_text(encoding="utf-8") == text
    assert gen.write_copies(tmp_path, "v4.6.0", text) == written


def test_the_pointer_refuses_to_move_backwards(tmp_path: Path) -> None:
    """`latest.md` is what a reader installs, so an older tag must not overwrite a newer one."""
    gen.write_copies(tmp_path, "v4.6.0", gen.preview("v4.6.0", CHANGELOG, REPO))
    with pytest.raises(gen.LatestIsNewer) as excinfo:
        gen.write_copies(tmp_path, "v4.5.0", gen.preview("v4.5.0", CHANGELOG, REPO))
    assert "4.6.0" in str(excinfo.value)
    assert (tmp_path / "docs/announcements/latest.md").read_text(encoding="utf-8") == gen.preview(
        "v4.6.0", CHANGELOG, REPO
    ), "the refusal must not have touched the file"


def test_preview_needs_the_repository_it_links_to(tmp_path: Path) -> None:
    """No slug, no derivable URL -- and no invented slug either."""
    with pytest.raises(SystemExit) as excinfo:
        gen.main(["--preview", "v4.6.0", "--repository", ""])
    assert "repository" in str(excinfo.value).lower()


def test_the_tag_shape_is_validated_before_anything_is_written(
    tmp_path: Path,
) -> None:
    """A malformed tag must fail before a file appears anywhere, including in this repo."""
    with pytest.raises(SystemExit):
        gen.main(["--preview", "4.6.0", "--repository", REPO, "--root", str(tmp_path)])
    assert not (tmp_path / "docs").exists()


def test_the_shipped_changelog_can_render_the_shipped_copy(tmp_path: Path) -> None:
    """The real file, the real heading, the real section: no fixture-only pass.

    v4.5.0's CHANGELOG section exists (§151 moved the released entries out of `## Unreleased`), so a
    preview of v4.5.0 must produce a copy whose highlights are that section's own text.
    """
    changelog = Path("CHANGELOG.md").read_text(encoding="utf-8")
    text = gen.preview("v4.5.0", changelog, REPO)
    assert gen.title_version(text) == "4.5.0"
    assert "Released" not in text
    assert "### Fixed — release gating" in text, "highlights carry no content from the section"


def test_a_long_section_is_cut_at_a_paragraph_and_stays_shareable() -> None:
    """The copy is a one-page announcement, not a mirror of the changelog.

    Measured before this bound existed: rendering v4.5.0 from its own CHANGELOG section produced
    58,971 characters, because the section runs to ~660 lines. Highlights are therefore bounded and
    cut at a line boundary, with the source named so nothing is presented as the whole record.
    """
    changelog = Path("CHANGELOG.md").read_text(encoding="utf-8")
    text = gen.preview("v4.5.0", changelog, REPO)
    assert len(text) < 4000, f"the copy is {len(text)} chars -- a page nobody shares"
    assert "CHANGELOG.md" in text, "a truncated summary must point at the full record"
    highlights = text.split("## Highlights\n", 1)[1].split("\n\n## Verify the release", 1)[0]
    assert highlights.rstrip().endswith("…"), highlights[-80:]
    assert not highlights.rstrip().endswith("\n\n"), "the cut landed mid-blank-line"


def test_publish_yml_no_longer_writes_the_default_branch() -> None:
    """The wiring this change is about: the release workflow reads its tree, it does not push prose.

    Asserted against the file rather than remembered: a step deleted from the workflow while its
    verification survives is the shape of a gate that stops firing.
    """
    workflow = Path(".github/workflows/publish.yml").read_text(encoding="utf-8")
    assert "contents/" not in workflow, "a contents-API write to the default branch is still wired"
    assert "generate_release_announcement.py" in workflow, (
        "the workflow stopped checking the copy that ships with the tag"
    )
    assert "pull-requests: write" not in workflow, (
        "a bot-opened PR would carry no `ci` check, so it could not merge cleanly (§151)"
    )


def test_preview_writes_the_tree_without_touching_the_network(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path
) -> None:
    """The pipeline path is offline by construction: it renders from files in the repo."""
    monkeypatch.setattr(gen, "request_json", lambda *a, **k: pytest.fail("preview hit the API"))
    changelog = tmp_path / "CHANGELOG.md"
    changelog.write_text(CHANGELOG, encoding="utf-8")
    code = gen.main(
        [
            "--preview",
            "v4.6.0",
            "--repository",
            REPO,
            "--changelog",
            str(changelog),
            "--root",
            str(tmp_path),
        ]
    )
    assert code == 0
    assert (tmp_path / "docs/announcements/v4.6.0.md").is_file()
    assert (
        gen.title_version((tmp_path / "docs/announcements/latest.md").read_text(encoding="utf-8"))
        == "4.6.0"
    )
