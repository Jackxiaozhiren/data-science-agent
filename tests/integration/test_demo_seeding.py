def _tracked() -> set[str]:
    out = subprocess.run(
        ["git", "ls-files", "-z"],  # noqa: S603 - fixed argv, read-only, no shell
        cwd=REPO,
        capture_output=True,
        check=True,
    )
    return {item.decode() for item in out.stdout.split(b"\0") if item}


