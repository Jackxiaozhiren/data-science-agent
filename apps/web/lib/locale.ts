export function t(locale: Locale, key: string): string {
  const table = UI_STRINGS[locale] ?? UI_STRINGS.en;
  const value = table[key];
  if (value !== undefined) return value;
  // A missing key must be loud in the page and in the console, not a silent fallback to English: the whole
  // point of one dictionary is that an omission is noticed.
  return `⟨${key}⟩`;
}

/**
 * The label for a run status.
 *
 * `ANALYSIS_STATUSES` is a closed enum that this app already owns and a contract test already compares against
 * the backend, so its words are chrome and they belong in the dictionary. A value outside that set is data the
 * run produced, and it renders as itself: inventing a translation for a state nobody declared is worse than
 * showing the raw token.
 */
export function statusLabel(locale: Locale, status: string): string {
  const value = UI_STRINGS[locale]?.[`status.${normalizeStatus(status)}`];
  return value ?? status;
}

/**
 * The badge for one tool call, whose status is the engine's own closed pair (`Literal["ok", "error"]` in
 * `dsa_agent/state.py`), not a value that came out of the visitor's data.
 *
 * Same shape as `statusLabel`: anything the producer does not declare is passed through rather than invented --
 * a token the web has never seen is worth reading exactly as it arrived, and translating it would be guessing.
 */
export function callStatusLabel(locale: Locale, status: string): string {
  const value = UI_STRINGS[locale]?.[`call.${status}`];
  return value ?? status;
}

/** The id the browser is already using, or the default when the cookie is absent or malformed. */
export function browserLocale(): Locale {
  if (typeof document === "undefined") return "en";
  const prefix = `${LOCALE_COOKIE}=`;
  for (const part of document.cookie.split(";")) {
    const entry = part.trim();
    if (entry.startsWith(prefix)) return normalizeLocale(entry.slice(prefix.length));
  }
  return "en";
}

/** Remember the choice and re-render in it. A reload is honest here; a half-translated page is not. */
export function storeLocale(locale: Locale): void {
  document.cookie = `${LOCALE_COOKIE}=${locale}; path=/; max-age=31536000; samesite=lax`;
}
